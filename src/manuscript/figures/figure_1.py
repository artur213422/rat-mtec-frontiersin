from pathlib import Path

from src.common.paths import PROJECT_ROOT
from src.manuscript.figures.layout.build_layout import build_layout, fig_1_png
from src.manuscript.figures.layout.panel_layout import FigureLayout

from src.manuscript.panels.fig_01.gsea_overview.create_gsea_overview import create_gsea_overview
from src.manuscript.panels.fig_01.gsea_table.create_gsea_table import create_gsea_table
from src.manuscript.panels.fig_01.isg_panel.create_isg_panel import create_isg_panel
from src.manuscript.shared.svg.save_png import save_png
from src.manuscript.shared.svg.svg import compose_svg

layout = FigureLayout(PROJECT_ROOT / "src/manuscript/figures/layout/figure_1_layout.json")

PANELS_OUTPUT: Path = PROJECT_ROOT / "manuscript_figures/panels/autogenerated/fig_1_panels"
FIGURE_FILE: Path = PROJECT_ROOT / "manuscript_figures/figures/autogenerated/figure_1.svg"
PNG_FILE: Path = PROJECT_ROOT / "manuscript_figures/figures/autogenerated/figure_1.png"


def build_figure() -> Path:
    build_layout(fig_1_png)

    panel_files: dict[str, Path] = {
        "A": create_gsea_overview(layout.get_panel("A"),    PANELS_OUTPUT / "A.svg"),
        "B": create_gsea_table(layout.get_panel("B"),       PANELS_OUTPUT / "B.svg"),
        "C": create_isg_panel(layout.get_panel("C"),        PANELS_OUTPUT / "C.svg")
    }

    compose_svg(layout, panel_files, FIGURE_FILE)
    save_png(FIGURE_FILE, PNG_FILE)
    return FIGURE_FILE


if __name__ == "__main__":
    print(build_figure())
