from pathlib import Path

from src.common.paths import PROJECT_ROOT
from src.manuscript.figures.layout.panel_layout import FigureLayout
from src.manuscript.figures.layout.build_layout import build_layout, fig_2_png
from src.manuscript.panels.fig_02.aire_distribution.create_aire_distribution import create_aire_distribution
from src.manuscript.panels.fig_02.keratin_loci.create_keratin_loci import create_keratin_loci
from src.manuscript.shared.svg.save_png import save_png
from src.manuscript.shared.svg.svg import compose_svg
from src.manuscript.panels.fig_02.genomic_windows.create_genomic_clusters import create_genomic_clusters

layout = FigureLayout(PROJECT_ROOT / "src/manuscript/figures/layout/figure_2_layout.json")

PANELS_OUTPUT: Path = PROJECT_ROOT / "manuscript_figures/panels/autogenerated/fig_2_panels"
FIGURE_FILE: Path = PROJECT_ROOT / "manuscript_figures/figures/autogenerated/figure_2.svg"
PNG_FILE: Path = PROJECT_ROOT / "manuscript_figures/figures/autogenerated/figure_2.png"


def build_figure() -> Path:
    build_layout(fig_2_png)

    panel_files: dict[str, Path] = {
        "A": create_aire_distribution(layout.get_panel("A"), PANELS_OUTPUT / "A.svg"),
        "B": create_genomic_clusters(layout.get_panel("B"),  PANELS_OUTPUT / "B.svg"),
        "C": create_keratin_loci(layout.get_panel("C"), PANELS_OUTPUT / "C.svg"),

    }
    compose_svg(layout, panel_files, FIGURE_FILE)
    save_png(FIGURE_FILE, PNG_FILE)

    return FIGURE_FILE

if __name__ == "__main__":
    print(build_figure())
