from pathlib import Path

from src.common.paths import PROJECT_ROOT
from src.manuscript.figures.layout.panel_layout import FigureLayout
from src.manuscript.panels.fig_03.tsa_heatmap.create_tsa_heatmap import create_tsa_heatmap
from src.manuscript.panels.fig_03.aps1_antigens.create_aps1_antigens import create_aps1_antigens
from src.manuscript.panels.fig_03.chemokine_panel.create_chemokine_panel import create_chemokine_panel
from src.manuscript.panels.fig_03.mimetic_panel.create_mimetic_panel import create_mimetic_panel
from src.manuscript.shared.svg.save_png import save_png
from src.manuscript.shared.svg.svg import compose_svg
from src.manuscript.figures.layout.build_layout import build_layout, fig_3_png, fig_3_json

layout = FigureLayout(PROJECT_ROOT / "src/manuscript/figures/layout/figure_3_layout.json")

PANELS_OUTPUT: Path = PROJECT_ROOT / "manuscript_figures/panels/autogenerated/fig_3_panels"
FIGURE_FILE: Path = PROJECT_ROOT / "manuscript_figures/figures/autogenerated/figure_3.svg"
PNG_FILE: Path = PROJECT_ROOT / "manuscript_figures/figures/autogenerated/figure_3.png"


def build_figure() -> Path:
    build_layout(fig_3_png)

    panel_files: dict[str, Path] = {
        "A": create_tsa_heatmap(layout.get_panel("A"),      PANELS_OUTPUT / "A.svg"),
        "B": create_mimetic_panel(layout.get_panel("B"), PANELS_OUTPUT / "B.svg"),
        "C": create_aps1_antigens(layout.get_panel("C"), PANELS_OUTPUT / "C.svg"),
        "D": create_chemokine_panel(layout.get_panel("D"),  PANELS_OUTPUT / "D.svg"),

    }

    compose_svg(layout, panel_files, FIGURE_FILE)
    save_png(FIGURE_FILE, PNG_FILE)

    return FIGURE_FILE

if __name__ == "__main__":
    print(build_figure())