from pathlib import Path

from src.common.paths import PROJECT_ROOT
from src.manuscript.figures.layout.build_layout import build_layout, sup_1_png, sup_1_json
from src.manuscript.figures.layout.panel_layout import FigureLayout
from src.manuscript.panels.sup_01.create_mice_windows import create_mice_window
from src.manuscript.shared.svg.save_png import save_png
from src.manuscript.shared.svg.svg import compose_svg

PANELS_OUTPUT: Path = PROJECT_ROOT / "manuscript_figures/panels/autogenerated/sup_1_panels"
FIGURE_FILE: Path = PROJECT_ROOT / "manuscript_figures/figures/autogenerated/sup_1.svg"
PNG_FILE: Path = PROJECT_ROOT / "manuscript_figures/figures/autogenerated/sup_1.png"


def build_figure() -> Path:
    build_layout(sup_1_png)
    layout = FigureLayout(sup_1_json)

    panel_files: dict[str, Path] = {
        "A": create_mice_window(layout.get_panel("A"),    PANELS_OUTPUT / "A.svg"),
    }

    compose_svg(layout, panel_files, FIGURE_FILE)
    save_png(FIGURE_FILE, PNG_FILE)
    return FIGURE_FILE


if __name__ == "__main__":
    print(build_figure())
