from pathlib import Path

from src.common.paths import PROJECT_ROOT
from src.manuscript.figures.layout.build_layout import build_layout, sup_2_png
from src.manuscript.figures.layout.panel_layout import FigureLayout
from src.manuscript.panels.sup_02.baran_gale_gsea import create_baran_gale_gsea
from src.manuscript.panels.sup_02.miclelson_gsea import create_michelson_gsea
from src.manuscript.shared.svg.save_png import save_png
from src.manuscript.shared.svg.svg import compose_svg

layout = FigureLayout(PROJECT_ROOT / "src/manuscript/figures/layout/sup_2_layout.json")

PANELS_OUTPUT: Path = PROJECT_ROOT / "manuscript_figures/panels/autogenerated/sup_2_panels"
FIGURE_FILE: Path = PROJECT_ROOT / "manuscript_figures/figures/autogenerated/sup_2.svg"
PNG_FILE: Path = PROJECT_ROOT / "manuscript_figures/figures/autogenerated/sup_2.png"


def build_figure() -> Path:
    build_layout(sup_2_png)

    panel_files: dict[str, Path] = {
        "A": create_michelson_gsea(layout.get_panel("A"),    PANELS_OUTPUT / "A.svg"),
        "B": create_baran_gale_gsea(layout.get_panel("B"),   PANELS_OUTPUT / "B.svg"),
    }

    compose_svg(layout, panel_files, FIGURE_FILE)
    save_png(FIGURE_FILE, PNG_FILE)
    return FIGURE_FILE


if __name__ == "__main__":
    print(build_figure())
